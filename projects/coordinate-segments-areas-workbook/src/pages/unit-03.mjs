const SHORT = '<span class="wline wline-short"></span>';

function blankGrid(opts) {
  return createGrid(opts).grid().axes();
}

function rectGrid(opts, [x1, y1], [x2, y2], labels = []) {
  const g = blankGrid(opts);
  g.polygon([[x1, y1], [x2, y1], [x2, y2], [x1, y2]]);
  const pts = [[x1, y1], [x2, y1], [x2, y2], [x1, y2]];
  pts.forEach(([x, y], i) => g.point(x, y, labels[i] ?? '', {
    dx: i === 0 || i === 3 ? -5 : 5,
    dy: i < 2 ? 10 : -5
  }));
  return g;
}

function triangleGrid(opts, vertices, labels = ['A', 'B', 'C']) {
  const g = blankGrid(opts);
  g.polygon(vertices);
  vertices.forEach(([x, y], i) => g.point(x, y, labels[i] ?? '', {
    dx: i === 0 ? -5 : 5,
    dy: i === 2 ? -6 : 10
  }));
  return g;
}

