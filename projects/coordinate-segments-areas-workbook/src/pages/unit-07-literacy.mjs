const UNIT = 'יחידה 7 — אוריינות: תכנון ומדידה';
const SHORT = '<span class="wline wline-short"></span>';

function grid(opts) {
  return createGrid(opts).grid().axes();
}

function labelPoint(g, label, x, y, dx = 5, dy = -6) {
  g.point(x, y, label, { dx, dy });
}

// עמוד 65: מגרש (0,0)-(12,8) ובו דשא, ערוגה משולשת ושביל.
function gardenGrid() {
  const g = grid({ xMin: -1, xMax: 13, yMin: -1, yMax: 9, unit: 12 });
  g.polygon([[0, 0], [12, 0], [12, 8], [0, 8]], { cls: 'cg-poly cg-dashed', fill: false });
  g.polygon([[1, 1], [7, 1], [7, 5], [1, 5]], { cls: 'cg-poly cg-highlight' });
  g.polygon([[8, 1], [12, 1], [8, 4]]);
  g.polygon([[1, 6], [11, 6], [11, 7], [1, 7]]);
  return g;
}

// עמוד 66: מגרש פעילות — מלבן (0,0)-(8,4) וטרפז עד (14,0), שער בתחתית.
function fieldGrid() {
  const g = grid({ xMin: -1, xMax: 15, yMin: -1, yMax: 5, unit: 13 });
  g.polygon([[0, 0], [14, 0], [11, 4], [0, 4]]);
  g.segment([8, 0], [8, 4], { dashed: true });
  g.segment([2, 0], [4, 0], { cls: 'cg-seg cg-highlight' });
  g.labelAt('שער', 3, 0, { anchor: 'middle', dy: 15, cls: 'cg-point-label' });
  return g;
}

// עמוד 67: מסלול רובוט עם תחנות בשני רביעים ותחנה מיותרת M.
function robotGrid() {
  const g = grid({ xMin: -5, xMax: 4, yMin: -4, yMax: 6, unit: 13 });
  g.segment([-4, 2], [3, 2]);
  g.segment([3, 2], [3, -3]);
  g.segment([3, -3], [-2, -3]);
  g.segment([3, 2], [3, 5], { dashed: true });
  g.segment([-4, 2], [-4, -3], { dashed: true });
  g.segment([-4, -3], [-2, -3], { dashed: true });
  labelPoint(g, 'S', -4, 2, -6, -6);
  labelPoint(g, 'A', 3, 2, 6, -6);
  labelPoint(g, 'B', 3, -3, 6, 13);
  labelPoint(g, 'C', -2, -3, -6, 13);
  labelPoint(g, 'M', 3, 5, 6, -6);
  labelPoint(g, 'E', -4, -3, -6, 13);
  return g;
}

// עמוד 68: מפה — מבנה, מגרש ושביל; כל משבצת 10 מטרים.
function mapGrid() {
  const g = grid({ xMin: -1, xMax: 12, yMin: -1, yMax: 8, unit: 12 });
  g.polygon([[1, 1], [5, 1], [5, 4], [1, 4]], { cls: 'cg-poly cg-highlight' });
  g.polygon([[6, 3], [11, 3], [11, 7], [6, 7]]);
  g.segment([5, 2], [11, 2], { dashed: true });
  g.labelAt('מבנה', 3, 2.5, { anchor: 'middle', cls: 'cg-point-label' });
  g.labelAt('מגרש', 8.5, 5, { anchor: 'middle', cls: 'cg-point-label' });
  return g;
}

// עמוד 69: גן מלבני (2,1)-(9,6) — הבעיה עם המידע העודף.
function infoGrid() {
  const g = grid({ xMin: -1, xMax: 10, yMin: -1, yMax: 7, unit: 12 });
  g.polygon([[2, 1], [9, 1], [9, 6], [2, 6]]);
  labelPoint(g, 'A', 2, 1, -5, 11); labelPoint(g, 'B', 9, 1, 5, 11);
  labelPoint(g, 'C', 9, 6, 5, -6); labelPoint(g, 'D', 2, 6, -6, -6);
  return g;
}

// עמוד 70: טרפז (1,1)-(11,1)-(8,5)-(4,5) עם קווי הפירוק.
function whoIsRightGrid() {
  const g = grid({ xMin: -1, xMax: 12, yMin: -1, yMax: 6, unit: 13 });
  g.polygon([[1, 1], [11, 1], [8, 5], [4, 5]]);
  g.segment([4, 1], [4, 5], { dashed: true });
  g.segment([8, 1], [8, 5], { dashed: true });
  labelPoint(g, 'A', 1, 1, -5, 11); labelPoint(g, 'B', 11, 1, 5, 11);
  labelPoint(g, 'C', 8, 5, 6, -6); labelPoint(g, 'D', 4, 5, -6, -6);
  return g;
}

