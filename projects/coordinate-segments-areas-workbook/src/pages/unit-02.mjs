const UNIT = 'יחידה 2 — מלבנים וריבועים במערכת הצירים';
const SHORT = '<span class="wline wline-short"></span>';
const FULL = '<span class="wline wline-full"></span>';

function blankGrid(opts) {
  return createGrid(opts).grid().axes();
}

/** מלבן שצלעותיו מקבילות לצירים, מקודקוד שמאלי־תחתון וקודקוד ימני־עליון. */
function rectGrid(opts, [x1, y1], [x2, y2], labels) {
  const g = blankGrid(opts);
  g.polygon([[x1, y1], [x2, y1], [x2, y2], [x1, y2]]);
  if (labels) {
    g.point(x1, y1, labels[0], { dx: -5, dy: 10 });
    g.point(x2, y1, labels[1], { dx: 5, dy: 10 });
    g.point(x2, y2, labels[2], { dx: 5, dy: -5 });
    g.point(x1, y2, labels[3], { dx: -5, dy: -5 });
  }
  return g;
}

