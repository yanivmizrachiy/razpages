const UNIT = 'יחידה 4 — מרובעים וצורות מורכבות';
const SHORT = '<span class="wline wline-short"></span>';

function grid(opts) {
  return createGrid(opts).grid().axes();
}

function labelPoint(g, label, x, y, dx = 5, dy = -6) {
  g.point(x, y, label, { dx, dy });
}

function parallelogramGrid() {
  const g = grid({ xMin: -1, xMax: 13, yMin: -1, yMax: 9, unit: 13 });
  g.polygon([[1, 2], [8, 2], [11, 7], [4, 7]]);
  g.segment([4, 7], [4, 2], { dashed: true });
  labelPoint(g, 'A', 1, 2, -5, 11); labelPoint(g, 'B', 8, 2, 5, 11);
  labelPoint(g, 'C', 11, 7, 5, -6); labelPoint(g, 'D', 4, 7, -5, -6);
  labelPoint(g, 'H', 4, 2, 0, 12);
  return g;
}

function completeParallelogramGrid() {
  const g = grid({ xMin: -1, xMax: 14, yMin: -1, yMax: 10, unit: 12 });
  g.segment([2, 2], [9, 2]);
  g.segment([2, 2], [5, 7]);
  labelPoint(g, 'A', 2, 2, -5, 11); labelPoint(g, 'B', 9, 2, 5, 11);
  labelPoint(g, 'D', 5, 7, -5, -6);
  return g;
}

function parallelogramRectangleGrid() {
  const g = grid({ xMin: -1, xMax: 13, yMin: -1, yMax: 9, unit: 13 });
  g.polygon([[1, 2], [8, 2], [11, 7], [4, 7]], { cls: 'cg-poly cg-highlight' });
  g.polygon([[1, 2], [8, 2], [8, 7], [1, 7]], { cls: 'cg-poly cg-dashed', fill: false });
  g.segment([4, 7], [4, 2], { dashed: true });
  g.segment([8, 7], [8, 2], { dashed: true });
  labelPoint(g, 'A', 1, 2, -5, 11); labelPoint(g, 'B', 8, 2, 5, 11);
  labelPoint(g, 'C', 11, 7, 5, -6); labelPoint(g, 'D', 4, 7, -5, -6);
  return g;
}

function trapezoidGrid() {
  const g = grid({ xMin: -1, xMax: 12, yMin: -1, yMax: 9, unit: 14 });
  g.polygon([[1, 2], [10, 2], [8, 7], [3, 7]]);
  g.segment([3, 7], [3, 2], { dashed: true });
  labelPoint(g, 'A', 1, 2, -5, 11); labelPoint(g, 'B', 10, 2, 5, 11);
  labelPoint(g, 'C', 8, 7, 5, -6); labelPoint(g, 'D', 3, 7, -5, -6);
  labelPoint(g, 'H', 3, 2, 0, 12);
  return g;
}

function trapezoidDecompositionGrid() {
  const g = grid({ xMin: -1, xMax: 12, yMin: -1, yMax: 9, unit: 14 });
  g.polygon([[1, 2], [10, 2], [8, 7], [3, 7]], { cls: 'cg-poly cg-highlight' });
  g.segment([3, 7], [3, 2], { dashed: true });
  g.segment([8, 7], [8, 2], { dashed: true });
  labelPoint(g, 'A', 1, 2, -5, 11); labelPoint(g, 'B', 10, 2, 5, 11);
  labelPoint(g, 'C', 8, 7, 5, -6); labelPoint(g, 'D', 3, 7, -5, -6);
  return g;
}

function trapezoidPerimeterGrid() {
  const g = grid({ xMin: -2, xMax: 12, yMin: -1, yMax: 8, unit: 13 });
  g.polygon([[0, 1], [10, 1], [7, 5], [3, 5]]);
  g.segment([3, 5], [3, 1], { dashed: true });
  g.segment([7, 5], [7, 1], { dashed: true });
  labelPoint(g, 'A', 0, 1, -5, 11); labelPoint(g, 'B', 10, 1, 5, 11);
  labelPoint(g, 'C', 7, 5, 5, -6); labelPoint(g, 'D', 3, 5, -5, -6);
  return g;
}

