const UNIT = 'יחידה 6 — צורות מורכבות';
const SHORT = '<span class="wline wline-short"></span>';

function grid(opts) {
  return createGrid(opts).grid().axes();
}

function labelPoint(g, label, x, y, dx = 5, dy = -6) {
  g.point(x, y, label, { dx, dy });
}

// עמוד 59: סביבון — גוף (2,4)-(10,8), חוד (6,1), ידית (5,8)-(7,10).
function spinnerGrid() {
  const g = grid({ xMin: -1, xMax: 11, yMin: -1, yMax: 11, unit: 12 });
  g.polygon([[2, 4], [10, 4], [10, 8], [2, 8]]);
  g.polygon([[2, 4], [10, 4], [6, 1]]);
  g.polygon([[5, 8], [7, 8], [7, 10], [5, 10]], { cls: 'cg-poly cg-highlight' });
  return g;
}

// עמוד 60: חץ — מלבן (1,3)-(8,7) וראש משולש כפול עד (12,5).
function arrowGrid() {
  const g = grid({ xMin: -1, xMax: 13, yMin: -1, yMax: 10, unit: 12 });
  g.polygon([[1, 3], [8, 3], [8, 1], [12, 5], [8, 9], [8, 7], [1, 7]]);
  g.segment([8, 1], [8, 9], { dashed: true });
  g.segment([8, 5], [12, 5], { dashed: true });
  return g;
}

// עמוד 61: מסגרת — מלבן (2,2)-(10,8) עם חור (4,4)-(8,6).
function frameGrid() {
  const g = grid({ xMin: -1, xMax: 11, yMin: -1, yMax: 9, unit: 12 });
  g.polygon([[2, 2], [10, 2], [10, 8], [2, 8]]);
  g.polygon([[4, 4], [8, 4], [8, 6], [4, 6]], { cls: 'cg-poly cg-dashed', fill: false });
  return g;
}

// עמוד 61: צורת L (1,1)-(9,1)-(9,4)-(5,4)-(5,7)-(1,7) עם קווי חלוקה.
function lShapeGrid() {
  const g = grid({ xMin: -1, xMax: 10, yMin: -1, yMax: 8, unit: 13 });
  g.polygon([[1, 1], [9, 1], [9, 4], [5, 4], [5, 7], [1, 7]]);
  g.segment([1, 4], [5, 4], { dashed: true });
  g.segment([5, 1], [5, 4], { dashed: true });
  return g;
}

// עמוד 62: מדרגות (0,0)…(0,8) בתוך מלבן חוסם מקווקו 10×8.
function stairsGrid() {
  const g = grid({ xMin: -1, xMax: 11, yMin: -1, yMax: 9, unit: 13 });
  g.polygon([[0, 0], [10, 0], [10, 8], [0, 8]], { cls: 'cg-poly cg-dashed', fill: false });
  g.polygon([[0, 0], [10, 0], [10, 3], [6, 3], [6, 6], [3, 6], [3, 8], [0, 8]]);
  return g;
}

// עמוד 63: שלוש צורות ששטחן 24 — מלבן 4×6, מלבן 12×2 וצורת L.
function threeShapesGrid() {
  const g = grid({ xMin: -1, xMax: 13, yMin: -1, yMax: 11, unit: 11 });
  g.polygon([[0, 0], [4, 0], [4, 6], [0, 6]]);
  g.polygon([[0, 8], [12, 8], [12, 10], [0, 10]]);
  g.polygon([[6, 0], [12, 0], [12, 3], [9, 3], [9, 5], [6, 5]], { cls: 'cg-poly cg-highlight' });
  g.labelAt('א', 2, 3, { anchor: 'middle', cls: 'cg-point-label' });
  g.labelAt('ב', 6, 9, { anchor: 'middle', cls: 'cg-point-label' });
  g.labelAt('ג', 7.5, 1.5, { anchor: 'middle', cls: 'cg-point-label' });
  return g;
}

// עמוד 63: צורת L ששטחה 24 והיקפה 28 — בדיוק כמו מלבן 12×2.
function equalPairGrid() {
  const g = grid({ xMin: -1, xMax: 9, yMin: -1, yMax: 7, unit: 13 });
  g.polygon([[0, 0], [8, 0], [8, 2], [2, 2], [2, 6], [0, 6]]);
  return g;
}

// עמוד 64: מקבילית (1,1)-(6,1)-(8,4)-(3,4) וטרפז (0,6)-(9,6)-(6,10)-(3,10).
function quadsAssessGrid() {
  const g = grid({ xMin: -1, xMax: 10, yMin: -1, yMax: 11, unit: 11 });
  g.polygon([[1, 1], [6, 1], [8, 4], [3, 4]]);
  g.segment([3, 4], [3, 1], { dashed: true });
  labelPoint(g, 'P', 1, 1, -5, 11); labelPoint(g, 'Q', 6, 1, 5, 11);
  labelPoint(g, 'R', 8, 4, 6, -6); labelPoint(g, 'S', 3, 4, -6, -6);
  g.polygon([[0, 6], [9, 6], [6, 10], [3, 10]]);
  g.segment([3, 10], [3, 6], { dashed: true });
  labelPoint(g, 'A', 0, 6, -5, 11); labelPoint(g, 'B', 9, 6, 5, 11);
  labelPoint(g, 'C', 6, 10, 6, -6); labelPoint(g, 'D', 3, 10, -6, -6);
  return g;
}

// עמוד 64: דלתון (5,0)-(8,3)-(5,10)-(2,3) ובית — מלבן (1,1)-(7,4) וגג עד (4,6).
function kiteAssessGrid() {
  const g = grid({ xMin: -1, xMax: 10, yMin: -1, yMax: 11, unit: 11 });
  g.polygon([[5, 0], [8, 3], [5, 10], [2, 3]]);
  g.segment([5, 0], [5, 10], { dashed: true });
  g.segment([2, 3], [8, 3], { dashed: true });
  return g;
}

function houseGrid() {
  const g = grid({ xMin: -1, xMax: 9, yMin: -1, yMax: 8, unit: 12 });
  g.polygon([[1, 1], [7, 1], [7, 4], [1, 4]]);
  g.polygon([[1, 4], [7, 4], [4, 6]]);
  return g;
}

