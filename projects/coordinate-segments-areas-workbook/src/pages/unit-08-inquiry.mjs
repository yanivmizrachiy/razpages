function grid(opts) {
  return createGrid(opts).grid().axes();
}

function labelPoint(g, label, x, y, dx = 5, dy = -6) {
  g.point(x, y, label, { dx, dy });
}

// עמוד 71: דוגמה נגדית לטענה 2 — ריבוע 6×6 ומלבן 2×10, שניהם בהיקף 24.
function counterGridP71() {
  const g = grid({ xMin: -1, xMax: 11, yMin: -1, yMax: 11, unit: 11 });
  g.polygon([[0, 0], [6, 0], [6, 6], [0, 6]]);
  g.polygon([[8, 0], [10, 0], [10, 10], [8, 10]], { cls: 'cg-poly cg-highlight' });
  return g;
}

// עמוד 72: הבסיס A(1,1)–B(7,1) והישר המקווקו y=6 שעליו כל נקודה C מתאימה.
function lineCGrid() {
  const g = grid({ xMin: -1, xMax: 10, yMin: -1, yMax: 8, unit: 12 });
  g.segment([1, 1], [7, 1]);
  g.segment([-1, 6], [10, 6], { dashed: true });
  g.point(3, 6, 'C?', { dx: 6, dy: -6 });
  labelPoint(g, 'A', 1, 1, -5, 13); labelPoint(g, 'B', 7, 1, 5, 13);
  return g;
}

// עמוד 73: מערכת ריקה רחבה לתכנון המתחם — כולל תחום שלילי.
function openPlanGrid() {
  return grid({ xMin: -6, xMax: 10, yMin: -6, yMax: 6, unit: 11 });
}

// עמוד 74: מפת שכונת המדע — בית ספר, פארק ובריכה בשני רביעים.
function neighborhoodGrid() {
  const g = grid({ xMin: -6, xMax: 10, yMin: -6, yMax: 7, unit: 11 });
  g.polygon([[-4, 1], [2, 1], [2, 5], [-4, 5]]);
  g.polygon([[3, 1], [9, 1], [5, 5]], { cls: 'cg-poly cg-highlight' });
  g.polygon([[-5, -5], [1, -5], [-1, -2], [-5, -2]]);
  g.labelAt('בית הספר', -1, 3, { anchor: 'middle', cls: 'cg-point-label' });
  g.labelAt('הפארק', 5.6, 2.2, { anchor: 'middle', cls: 'cg-point-label' });
  g.labelAt('הבריכה', -2, -3.6, { anchor: 'middle', cls: 'cg-point-label' });
  return g;
}

// עמוד 75: קטע ומלבן (חוצה את ציר X) למבחן המסכם.
function finalGridA() {
  const g = grid({ xMin: -4, xMax: 8, yMin: -3, yMax: 7, unit: 12 });
  g.segment([-3, 5], [4, 5]);
  g.polygon([[1, -2], [6, -2], [6, 3], [1, 3]]);
  labelPoint(g, 'P', -3, 5, -6, -6); labelPoint(g, 'Q', 4, 5, 6, -6);
  return g;
}

// עמוד 75: משולש ישר-זווית ודלתון למבחן המסכם.
function finalGridB() {
  const g = grid({ xMin: -1, xMax: 12, yMin: -1, yMax: 7, unit: 12 });
  g.polygon([[0, 0], [6, 0], [0, 4]]);
  g.polygon([[9, 0], [11, 2], [9, 6], [7, 2]]);
  g.segment([9, 0], [9, 6], { dashed: true });
  g.segment([7, 2], [11, 2], { dashed: true });
  return g;
}

