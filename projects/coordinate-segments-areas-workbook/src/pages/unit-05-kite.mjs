const UNIT = 'יחידה 5 — הדלתון במערכת הצירים';
const SHORT = '<span class="wline wline-short"></span>';

function grid(opts) {
  return createGrid(opts).grid().axes();
}

function labelPoint(g, label, x, y, dx = 5, dy = -6) {
  g.point(x, y, label, { dx, dy });
}

// עמוד 53: דלתון A(6,1) B(9,4) C(6,9) D(3,4) — אלכסונים 8 ו-6, מפגש (6,4).
function kiteDiagonalsGrid() {
  const g = grid({ xMin: -1, xMax: 11, yMin: -1, yMax: 10, unit: 13 });
  g.polygon([[6, 1], [9, 4], [6, 9], [3, 4]]);
  g.segment([6, 1], [6, 9], { dashed: true });
  g.segment([3, 4], [9, 4], { dashed: true });
  labelPoint(g, 'A', 6, 1, 6, 13); labelPoint(g, 'B', 9, 4, 6, -6);
  labelPoint(g, 'C', 6, 9, 6, -6); labelPoint(g, 'D', 3, 4, -6, -6);
  labelPoint(g, 'M', 6, 4, 7, 14);
  return g;
}

// עמוד 54: דלתון A(1,4) B(4,7) C(11,4) D(4,1) בתוך מלבן חוסם 10×6.
function kiteBoundingGrid() {
  const g = grid({ xMin: -1, xMax: 12, yMin: -1, yMax: 8, unit: 13 });
  g.polygon([[1, 1], [11, 1], [11, 7], [1, 7]], { cls: 'cg-poly cg-dashed', fill: false });
  g.polygon([[1, 4], [4, 7], [11, 4], [4, 1]], { cls: 'cg-poly cg-highlight' });
  g.segment([1, 4], [11, 4], { dashed: true });
  g.segment([4, 7], [4, 1], { dashed: true });
  labelPoint(g, 'A', 1, 4, -6, -6); labelPoint(g, 'B', 4, 7, 5, -6);
  labelPoint(g, 'C', 11, 4, 6, -6); labelPoint(g, 'D', 4, 1, 5, 13);
  return g;
}

// עמוד 54: דלתון שני E(4,1) F(6,3) G(4,7) H(2,3) — אלכסונים 6 ו-4, מלבן חוסם 4×6.
function secondBoundingGrid() {
  const g = grid({ xMin: -1, xMax: 7, yMin: -1, yMax: 8, unit: 14 });
  g.polygon([[2, 1], [6, 1], [6, 7], [2, 7]], { cls: 'cg-poly cg-dashed', fill: false });
  g.polygon([[4, 1], [6, 3], [4, 7], [2, 3]], { cls: 'cg-poly cg-highlight' });
  g.segment([4, 1], [4, 7], { dashed: true });
  g.segment([2, 3], [6, 3], { dashed: true });
  labelPoint(g, 'E', 4, 1, 6, 13); labelPoint(g, 'F', 6, 3, 6, -6);
  labelPoint(g, 'G', 4, 7, 6, -6); labelPoint(g, 'H', 2, 3, -6, -6);
  return g;
}

// עמוד 55: דלתון A(4,-2) B(7,1) C(4,7) D(1,1) — האלכסון האנכי חוצה את ציר X.
function kiteTrianglesGrid() {
  const g = grid({ xMin: -2, xMax: 9, yMin: -3, yMax: 8, unit: 13 });
  g.polygon([[4, -2], [7, 1], [4, 7], [1, 1]]);
  g.segment([4, -2], [4, 7], { dashed: true });
  g.segment([1, 1], [7, 1], { dashed: true });
  labelPoint(g, 'A', 4, -2, 6, 13); labelPoint(g, 'B', 7, 1, 6, -6);
  labelPoint(g, 'C', 4, 7, 6, -6); labelPoint(g, 'D', 1, 1, -6, -6);
  labelPoint(g, 'M', 4, 1, 7, 14);
  return g;
}

// עמוד 56: מערכת ריקה לבניית דלתון ששטחו 24.
function emptyBuildGrid() {
  return grid({ xMin: -1, xMax: 12, yMin: -1, yMax: 8, unit: 13 });
}

// עמוד 57: מעוין A(6,0) B(9,4) C(6,8) D(3,4) — כל צלע 5 (ניצבים 3 ו-4).
function rhombusGrid() {
  const g = grid({ xMin: -1, xMax: 11, yMin: -1, yMax: 9, unit: 13 });
  g.polygon([[6, 0], [9, 4], [6, 8], [3, 4]]);
  g.segment([6, 0], [6, 8], { dashed: true });
  g.segment([3, 4], [9, 4], { dashed: true });
  g.segment([6, 0], [9, 0], { dashed: true });
  g.segment([9, 0], [9, 4], { dashed: true });
  labelPoint(g, 'A', 6, 0, -6, 13); labelPoint(g, 'B', 9, 4, 6, -6);
  labelPoint(g, 'C', 6, 8, 6, -6); labelPoint(g, 'D', 3, 4, -6, -6);
  return g;
}

// עמוד 57: אותם אלכסונים (8 ו-6), נקודת מפגש אחרת — A(6,0) B(9,2) C(6,8) D(3,2).
function shiftedKiteGrid() {
  const g = grid({ xMin: -1, xMax: 11, yMin: -1, yMax: 9, unit: 13 });
  g.polygon([[6, 0], [9, 2], [6, 8], [3, 2]]);
  g.segment([6, 0], [6, 8], { dashed: true });
  g.segment([3, 2], [9, 2], { dashed: true });
  labelPoint(g, 'A', 6, 0, -6, 13); labelPoint(g, 'B', 9, 2, 6, -6);
  labelPoint(g, 'C', 6, 8, 6, -6); labelPoint(g, 'D', 3, 2, -6, -6);
  return g;
}

// עמוד 58: סביבון — מעוין (אלכסונים 8 ו-6) וריבוע ידית 2×2 הנוגע בקודקוד העליון.
function dreidelGrid() {
  const g = grid({ xMin: -1, xMax: 11, yMin: -1, yMax: 11, unit: 12 });
  g.polygon([[6, 0], [9, 4], [6, 8], [3, 4]]);
  g.polygon([[5, 8], [7, 8], [7, 10], [5, 10]], { cls: 'cg-poly cg-highlight' });
  g.segment([6, 0], [6, 8], { dashed: true });
  g.segment([3, 4], [9, 4], { dashed: true });
  return g;
}

// עמוד 58: מרובע A(1,4) B(4,8) C(9,4) D(4,1) — אלכסונים מאונכים אך אינו דלתון.
function notKiteGrid() {
  const g = grid({ xMin: -1, xMax: 10, yMin: -1, yMax: 9, unit: 13 });
  g.polygon([[1, 4], [4, 8], [9, 4], [4, 1]]);
  g.segment([1, 4], [9, 4], { dashed: true });
  g.segment([4, 8], [4, 1], { dashed: true });
  labelPoint(g, 'A', 1, 4, -6, -6); labelPoint(g, 'B', 4, 8, 5, -6);
  labelPoint(g, 'C', 9, 4, 6, -6); labelPoint(g, 'D', 4, 1, 5, 13);
  return g;
}

